import { withAlpha } from "./colorHelpers";

/**
 * Convert the plain-text paper content into a styled HTML document for the
 * live preview iframe.
 *
 * @param {string} text       - Raw paper text from the editor
 * @param {object} meta       - Exam metadata (instituteName, subjectName, …)
 * @param {string} color      - Brand hex color
 * @returns {string}          - Complete HTML string
 */
export function buildPreviewHtml(text, meta = {}, color = "#ff7f10") {
  if (!text) return "";

  // Strip diagram blocks from preview text
  const body = `
  <div class="paper-content">
    ${text}
  </div>
`;

const instituteName =
  meta.instituteName || "";

const subjectName =
  meta.subjectName || "Subject";

const examType =
  meta.examType || "Examination";

const semester =
  meta.semester || "";

const acadYear =
  meta.academicYear || "";

const duration =
  meta.duration || "3 Hours";
  const totalMarks    = meta.totalMarks        || 100;

  return `<!DOCTYPE html><html><head><meta charset="UTF-8">
<style>
  *{
    box-sizing:border-box;
    margin:0;
    padding:0;
  }

  body{
    font-family:Georgia,"Times New Roman",serif;
    background:#fff;
    padding:28px 32px;
    color:#111;
    font-size:13px;
  }

  @media print{
    body{
      padding:16px;
    }
  }

  .paper-content{
    margin-top:18px;
  }

  .paper-content p{
    margin:0 0 10px;
    line-height:1.7;
  }

  .paper-content h1,
  .paper-content h2,
  .paper-content h3{
    margin:16px 0 10px;
    font-weight:700;
  }

  .paper-content ul,
  .paper-content ol{
    padding-left:24px;
    margin:8px 0;
  }

  .paper-content table{
    width:100%;
    border-collapse:collapse;
    margin:14px 0;
  }

  .paper-content td,
  .paper-content th{
    border:1px solid #d1d5db;
    padding:8px;
  }

  .paper-content strong{
    font-weight:700;
  }
</style></head><body>
<div style="text-align:center;border-bottom:2px solid ${color};padding-bottom:14px;margin-bottom:16px">
  ${instituteName ? `<div style="font-size:17px;font-weight:700;color:#1e40af;margin-bottom:4px;letter-spacing:0.2px">${instituteName}</div>` : ""}
  <div style="font-size:16px;font-weight:700;color:#111;margin-bottom:4px">${examType}</div>
  <div style="font-size:13px;font-weight:600;color:#333;margin-bottom:6px">Subject: ${subjectName}</div>
  <div style="display:flex;justify-content:center;gap:24px;font-size:11.5px;color:#555">
    ${semester ? `<span>Semester: ${semester}</span>` : ""}
    ${acadYear ? `<span>Academic Year: ${acadYear}</span>` : ""}
    <span>Duration: ${duration}</span>
    <span>Total Marks: ${totalMarks}</span>
  </div>
</div>
${body}
<div style="text-align:center;border-top:1px solid #e5e7eb;margin-top:24px;padding-top:10px;font-size:11px;color:#9ca3af">
  — End of Question Paper — &nbsp;|&nbsp; Generated by grAdelytIcs
</div>
</body></html>`;
}